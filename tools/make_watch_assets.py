"""Builds the Apple Watch app's shared resources in app/ios/Shared from the web app:

- Penguins.xcassets: the eight hand-drawn penguins, cropped to one shared frame and scaled down (crop and
  resize only; the drawings aren't altered), and the raindrop tile as it is.
- <lproj>/Localizable.strings: the strings the watch shows, taken from web/app/lang/<tag>.js so the watch
  says what the phone says. {t} becomes %@.
- <lproj>/InfoPlist.strings: copied from the iPhone app (the location permission text).

Usage: python3 -I tools/make_watch_assets.py   (run again after changing the drawings or the translations)
"""
import json
import pathlib
import re
import shutil

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
ART = ROOT / "web/app/images"
LANG = ROOT / "web/app/lang"
SHARED = ROOT / "app/ios/Shared"
IOS = ROOT / "app/ios/WeatherPenguin"

OUTFITS = ["naked", "cold", "jacket", "jacket_rain", "warm", "warm_rain", "hot", "hot_rain"]
WIDTH = 420  # px; the watch shows them at up to about 200 pt wide

# The English keys the watch uses (the same keys as web/app/main.js and rules.js)
KEYS = [
    "Today", "Tomorrow", "High of {t}", "Low of {t}", "Rain likely.", "Loading...", "Try Again", "Error",
    "Location Access Denied", "Please enable location services so the penguin can check your weather.",
    "Failed to get location.", "Couldn't get the weather. Please try again in a moment.",
    "Bundle up: sweater, scarf and hat.", "Grab a jacket.", "Raincoat and rain hat today.", "T-shirt weather!",
    "Warm, but bring a rain poncho.", "Hot! Bikini weather.", "Hot and showery. Swim cap on.",
    "A penguin wearing nothing at all", "A penguin in a red sweater, striped scarf and yellow hat",
    "A penguin in a green jacket", "A penguin in a yellow raincoat and rain hat",
    "A penguin in a striped T-shirt with a heart", "A penguin in a blue hooded poncho",
    "A penguin in a polka-dot bikini", "A penguin in a polka-dot bikini, swim cap and goggles",
    "Mostly Cloudy", "Partly Cloudy", "Mostly Sunny", "Clear",  # the screenshot samples' conditions
]

# web/app/lang tag → .lproj folders
LPROJ = {"en": ["en"], "da": ["da"], "de": ["de"], "es": ["es"], "fi": ["fi"], "fr": ["fr"], "it": ["it"],
         "ja": ["ja"], "ko": ["ko"], "nb": ["nb"], "nl": ["nl"], "pl": ["pl"], "pt": ["pt-BR", "pt-PT"],
         "ru": ["ru"], "sv": ["sv"], "zh": ["zh-Hans"], "zh-Hant": ["zh-Hant"]}


def table(tag):
    if tag == "en":
        return {k: k for k in KEYS}
    src = (LANG / f"{tag}.js").read_text()
    body = src[src.index("{"): src.rindex("}") + 1]
    return json.loads(re.sub(r",\s*}$", "}", body))


def strings_literal(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    # pictures
    cat = SHARED / "Penguins.xcassets"
    shutil.rmtree(cat, ignore_errors=True)
    cat.mkdir(parents=True)
    (cat / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    drawings = {o: Image.open(ART / f"{o}.png").convert("RGBA") for o in OUTFITS}
    boxes = [im.getchannel("A").getbbox() for im in drawings.values()]
    frame = (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))
    height = round(WIDTH * (frame[3] - frame[1]) / (frame[2] - frame[0]))
    for o, im in drawings.items():
        d = cat / f"penguin-{o}.imageset"
        d.mkdir()
        im.crop(frame).resize((WIDTH, height), Image.LANCZOS).save(d / f"{o}.png", optimize=True)
        (d / "Contents.json").write_text(json.dumps({
            "images": [{"filename": f"{o}.png", "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
        }, indent=2) + "\n")

    # the raindrop tile (106x142 px), tiled behind the penguin when it rains. Marked 2x: watchOS catalogs keep
    # only 1x and 2x, so a 3x-only image is left out of the app. ContentView draws it smaller.
    d = cat / "raindrop.imageset"
    d.mkdir()
    shutil.copy(ART / "raindrop.png", d / "raindrop.png")
    (d / "Contents.json").write_text(json.dumps({
        "images": [{"filename": "raindrop.png", "idiom": "universal", "scale": "2x"}],
        "info": {"author": "xcode", "version": 1},
    }, indent=2) + "\n")

    # strings
    for tag, lprojs in LPROJ.items():
        t = table(tag)
        lines = [f"/* Generated by tools/make_watch_assets.py from web/app/lang/{tag}.js. Don't edit. */"]
        for k in KEYS:
            lines.append(f"{strings_literal(k.replace('{t}', '%@'))} = {strings_literal(t[k].replace('{t}', '%@'))};")
        for lp in lprojs:
            d = SHARED / f"{lp}.lproj"
            d.mkdir(exist_ok=True)
            (d / "Localizable.strings").write_text("\n".join(lines) + "\n")
            shutil.copy(IOS / f"{lp}.lproj" / "InfoPlist.strings", d / "InfoPlist.strings")
    print(f"{len(OUTFITS)} penguins at {WIDTH}x{height}, strings for {sum(len(v) for v in LPROJ.values())} languages")


if __name__ == "__main__":
    main()
